const LANG_NAMES = { 'zh-CN': '简体中文', 'zh-TW': '繁體中文', en: 'English', ja: '日本語' };

const DEFAULT_LOCALE = 'zh-CN';

// 保存済みの値・OS のロケールを、対応している 4 つのどれかに寄せる。繁体字(zh-TW/zh-HK/zh-MO/Hant)は zh-TW へ。
// 対応外は null を返し、呼び側が既定を決める(勝手に既定へ潰すと、
// 将来 UI を足したときに「なぜか切り替わらない」の原因になる)。
function normalizeLocale(raw) {
  const v = String(raw || '').trim();
  if (UI[v]) return v;
  const low = v.toLowerCase().replace('_', '-');
  if (low.startsWith('zh')) return /hant|tw|hk|mo/.test(low) ? 'zh-TW' : 'zh-CN';
  if (low.startsWith('ja')) return 'ja';
  if (low.startsWith('en')) return 'en';
  return null;
}

function uiStrings(locale) { return UI[normalizeLocale(locale) || DEFAULT_LOCALE] || UI[DEFAULT_LOCALE]; }

function supportedUiLocales() {
  return Object.keys(UI).map((id) => ({ id, label: LANG_NAMES[id] || id }));
}

// '{name}' 形式の差し込み。値が無いキーはそのまま残す(空文字に潰すと、
// 文章が意味不明になったときに原因が分からなくなる)。
function fmt(tpl, vars) {
  if (!tpl) return '';
  return String(tpl).replace(/\{(\w+)\}/g, (m, k) => (vars && vars[k] != null ? String(vars[k]) : m));
}

module.exports = { UI, LANG_NAMES, DEFAULT_LOCALE, uiStrings, supportedUiLocales, normalizeLocale, fmt };
